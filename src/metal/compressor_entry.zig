//! Sole C facade for the pure compressor owners. ABI names and argument order
//! are the existing ds4_gpu.h boundary; internal requests have named fields.
const std = @import("std");
const c = @import("metal_c");
const core = @import("compressor.zig");
const projection = @import("compressor_projection.zig");
const Tensor = @import("bridge.zig").Tensor;

export fn ds4_gpu_matmul_f16_pair_compressor_store_tensor(
    out_kv: ?*Tensor,
    out_score: ?*Tensor,
    state_kv: ?*Tensor,
    state_score: ?*Tensor,
    model_map: ?*const anyopaque,
    model_size: u64,
    weight_kv_offset: u64,
    weight_score_offset: u64,
    ape_offset: u64,
    ape_type: u32,
    in_dim: u64,
    width: u32,
    x: ?*const Tensor,
    ratio: u32,
    pos: u32,
) callconv(.c) c_int {
    return projection.pair(.{
        .pairs = .{ .{
            .out_kv = out_kv,
            .out_score = out_score,
            .state_kv = state_kv,
            .state_score = state_score,
            .weight_kv = weight_kv_offset,
            .weight_score = weight_score_offset,
            .ape = ape_offset,
            .ape_type = ape_type,
            .width = width,
        }, std.mem.zeroes(projection.Pair) },
        .map = model_map,
        .size = model_size,
        .input = in_dim,
        .x = x,
        .ratio = ratio,
        .pos = pos,
    });
}

