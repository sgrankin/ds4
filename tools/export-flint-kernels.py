#!/usr/bin/env python3
"""Export Flint's M4 Pro, M5 Pro and M5 Max resident decoders as standalone MSL.

Build-time conversion only: imports the upstream string transforms, never MLX,
loads no weights and creates no GPU objects. The checked-in output is what the
native engine compiles; serving has no Python or MLX dependency.

Usage: python3 tools/export-flint-kernels.py [../flint] [--profile m5-max]
Source: recursive-oss/rec e53663b262af4cb1ca498e596ca8b1a2d79e0800
(Apache-2.0). Keep the packet loop and BF16 boundaries intact when updating.
"""
import argparse
import ast
import importlib.util
import math
from pathlib import Path
import sys
import types


def load_transforms(directory):
    package = types.ModuleType("flint_export")
    package.__path__ = [str(directory)]
    sys.modules[package.__name__] = package

    def load(name):
        fullname = f"{package.__name__}.{name}"
        spec = importlib.util.spec_from_file_location(fullname, directory / f"{name}.py")
        module = importlib.util.module_from_spec(spec)
        sys.modules[fullname] = module
        spec.loader.exec_module(module)
        return module

    return {name: load(name) for name in (
        "shader_source", "kv_teams", "expert_teams", "resident_optimizations",
        "rank_routing", "mixed_bits", "activation_optimization", "resident_block",
    )}


def literal(source, name):
    for node in ast.parse(source).body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == name for target in node.targets
        ):
            return ast.literal_eval(node.value)
    raise ValueError(f"Missing upstream source literal {name}")


PROFILES = {
    "m4-pro": ("M4 Pro", 36, 32, False, "decode-m4-pro.metal", "_m4_pro"),
    "m5-pro": ("M5 Pro", 36, 32, True, "decode-m5-pro.metal", "_m5_pro"),
    "m5-max": ("M5 Max", 76, 64, True, "decode.metal", ""),
}


def render(text, workers, mlp_workers):
    values = dict(
        WORKERS=workers, GROUPS=workers * 8, THREADS=workers * 256,
        GROUP_THREADS=256, GROUP_SIMDS=8,
        KV_FIRST=0, PROFILE=0, SHORT_HEADS=4, LONG_HEADS=8, LONG_CONTEXT=1024,
        UNROLL=1, TEAM_MLP_WORKERS=mlp_workers, EPS="1e-06f",
        LOGBASE=f"{math.log2(10000.0)!r}f",
    )
    for phase in ("ATTENTION", "MERGE", "ROUTER", "MLP", "HEAD"):
        count = mlp_workers if phase in ("MLP", "HEAD") else workers
        values[phase + "_WORKERS"] = count
        values[phase + "_GROUPS"] = count * 8
    for key, value in values.items():
        text = text.replace(f"__{key}__", str(value))
    return text


PREAMBLE = """// Generated by tools/export-flint-kernels.py; edit the exporter, then regenerate.
// Derived from recursive-oss/rec e53663b262af4cb1ca498e596ca8b1a2d79e0800.
// Apache-2.0; see LICENSE.rec. No MLX runtime dependency.
// Fixed resident schedule: Apple M5 Max, 76 groups x 256 threads, 64 MLP/head groups.
#include <metal_stdlib>
using namespace metal;
typedef bfloat bfloat16_t;

// Match the BF16 math overloads used by the source runtime. In particular, the
// sigmoid's exp result is rounded to BF16 before the reciprocal. These three
// overloads are the dependency closure of MLX's bf16_math.h (Apple, MIT).
namespace metal {
inline bfloat16_t abs(bfloat16_t x) {
    return bfloat16_t(__metal_fabs(float(x), __METAL_MAYBE_FAST_MATH__));
}
inline bfloat16_t exp(bfloat16_t x) {
    return bfloat16_t(__metal_exp(float(x), __METAL_MAYBE_FAST_MATH__));
}
namespace fast {
inline bfloat16_t exp(bfloat16_t x) {
    return bfloat16_t(__metal_exp(float(x), __METAL_FAST_MATH__));
}
}
}
"""


def entry(name, body, packet=False, steering=False):
    arguments = [f"    const device uchar* bank{i} [[buffer({i})]]" for i in range(13)]
    arguments += [
        "    const device uint* metadata [[buffer(13)]]",
        *[f"    const device bfloat16_t* kv{i} [[buffer({14+i})]]" for i in range(4)],
        "    const device uint* parameters [[buffer(18)]]",
        "    const device bfloat16_t* silu_table [[buffer(19)]]",
        "    device uint* private_control [[buffer(20)]]",
        ("    const device float* sampling [[buffer(21)]]" if packet else
         "    const device uint* configuration [[buffer(21)]]"),
        f"    device bfloat16_t* {'block_logits' if packet else 'logits'} [[buffer(22)]]",
        f"    device bfloat16_t* {'block_trace' if packet else 'trace'} [[buffer(23)]]",
        "    device uint* diagnostic [[buffer(24)]]",
        "    device uint* profile [[buffer(25)]]",
        "    device bfloat16_t* workspace [[buffer(26)]]",
        "    device float* partials [[buffer(27)]]",
        "    device float* statistics [[buffer(28)]]",
        "    device uint* routing [[buffer(29)]]",
        *(["    const device float* steering [[buffer(30)]]"] if steering else []),
        "    uint thread_index_in_threadgroup [[thread_index_in_threadgroup]]",
        "    uint thread_index_in_simdgroup [[thread_index_in_simdgroup]]",
        "    uint simdgroup_index_in_threadgroup [[simdgroup_index_in_threadgroup]]",
        "    uint3 threadgroup_position_in_grid [[threadgroup_position_in_grid]]",
    ]
    return (f"\nkernel void {name}(\n" + ",\n".join(arguments) + ") {\n" + body
            + "\n}\n#undef SYNC\n#undef KV_TEAM_SYNC\n")


HELPERS = r"""
// Shared/dense SiLU uses the original BF16 sigmoid/multiply table. Construct on
// this GPU so exp/rounding follows the same Metal semantics as the decoder.
kernel void flint_init_silu(device bfloat16_t* table [[buffer(0)]],
                            uint i [[thread_position_in_grid]]) {
    if(i>=65536u)return;
    bfloat16_t g=as_type<bfloat16_t>(ushort(i));
    auto tail=1/(1+metal::exp(metal::abs(g)));
    bfloat16_t sig=g<0?tail:1-tail;
    table[i]=bfloat16_t(g*sig);
}
"""


STEERING_HELPER = r"""
// Every resident group already owns all 2048 output coordinates. Project in
// those registers, with a local reduction only: no new global phase or launch.
inline void flint_steer(thread float* values, const device float* direction,
                        float scale, uint tid, uint lane, uint sg,
                        threadgroup float* partial) {
    float dot=0.0f;
    for(uint j=0;j<8;++j) {
        uint i=(tid+(j/4)*256)*4+j%4;
        dot+=values[j]*direction[i];
    }
    dot=simd_sum(dot);
    if(lane==0)partial[sg]=dot;
    threadgroup_barrier(mem_flags::mem_threadgroup);
    dot=simd_sum(lane<8?partial[lane]:0.0f);
    for(uint j=0;j<8;++j) {
        uint i=(tid+(j/4)*256)*4+j%4;
        values[j]=float(bfloat16_t(values[j]-scale*direction[i]*dot));
    }
    // Scratch belongs only to steering. Existing layer/phase barriers separate
    // its next use; RMS uses its own reduction storage and cannot race this read.
}

// Model-free qualification uses the exact resident helper and coordinate map.
kernel void flint_steering_fixture(constant float& scale [[buffer(0)]],
    const device bfloat16_t* input [[buffer(1)]],
    const device float* direction [[buffer(2)]], device bfloat16_t* output [[buffer(3)]],
    uint tid [[thread_index_in_threadgroup]], uint lane [[thread_index_in_simdgroup]],
    uint sg [[simdgroup_index_in_threadgroup]]) {
    threadgroup float partial[8];
    float values[8];
    for(uint j=0;j<8;++j){uint i=(tid+(j/4)*256)*4+j%4;values[j]=float(input[i]);}
    flint_steer(values,direction,scale,tid,lane,sg,partial);
    for(uint j=0;j<8;++j){uint i=(tid+(j/4)*256)*4+j%4;output[i]=bfloat16_t(values[j]);}
}
"""


def steer_body(body):
    """Project the already-rounded residual after each selected sublayer."""
    attention = "for(uint j=0;j<8;++j){uint i=(tid+(j/4)*256)*4+j%4;h[j]=bfloat16_t(float(h[j])+float(o[i]));}"
    assert body.count(attention) == 1
    body = body.replace(attention, attention + """
            if(steering_scales[6]!=0.0f) {
                float residual[8];
                for(uint j=0;j<8;++j)residual[j]=float(h[j]);
                flint_steer(residual,steering+layer*2048,steering_scales[6],tid,lane,simdgroup_index_in_threadgroup,steering_reduction);
                for(uint j=0;j<8;++j)h[j]=bfloat16_t(residual[j]);
            }""")
    start = body.index("        {\n        if(sparse) {")
    end = body.index("\n    }\n    {rms_256_w4", start)
    block = body[start:end]
    assert block.count("h[j]=bfloat16_t(float(h[j])+float(mlp));") == 2
    block = block.replace("                if(group==0)trace[(layer+1)*2048+i]=h[j];\n", "")
    block = block[:-len("        }")] + """        if(steering_scales[7]!=0.0f) {
            float residual[8];
            for(uint j=0;j<8;++j)residual[j]=float(h[j]);
            flint_steer(residual,steering+layer*2048,steering_scales[7],tid,lane,simdgroup_index_in_threadgroup,steering_reduction);
            for(uint j=0;j<8;++j)h[j]=bfloat16_t(residual[j]);
        }
        if(group==0)for(uint j=0;j<8;++j){uint i=(tid+(j/4)*256)*4+j%4;trace[(layer+1)*2048+i]=h[j];}
        }"""
    return body[:start] + block + body[end:]


ADDITIVE_HELPER = r"""
// Add a layer-budgeted direction to the already-rounded residual stream.
inline bfloat16_t flint_additive(bfloat16_t value,float direction,float scale) {
    return bfloat16_t(float(value)+scale*direction);
}
kernel void flint_additive_fixture(constant float& scale [[buffer(0)]],
    const device bfloat16_t* input [[buffer(1)]], const device float* direction [[buffer(2)]],
    device bfloat16_t* output [[buffer(3)]], uint i [[thread_position_in_grid]]) {
    if(i<2048u)output[i]=flint_additive(input[i],direction[i],scale);
}
"""


def additive_body(body):
    """Preserve BF16 publication; test the uniform scale once per sublayer."""
    attention = "for(uint j=0;j<8;++j){uint i=(tid+(j/4)*256)*4+j%4;h[j]=bfloat16_t(float(h[j])+float(o[i]));}"
    assert body.count(attention) == 1
    body = body.replace(attention, attention + """
            const float attention_scale=steering_scales[6];
            if(attention_scale!=0.0f)for(uint j=0;j<8;++j) {
                uint i=(tid+(j/4)*256)*4+j%4;
                h[j]=flint_additive(h[j],steering[layer*2048+i],attention_scale);
            }""")
    start = body.index("        {\n        if(sparse) {")
    end = body.index("\n    }\n    {rms_256_w4", start)
    block = body[start:end]
    assert block.count("h[j]=bfloat16_t(float(h[j])+float(mlp));") == 2
    assert block.count("                if(group==0)trace[(layer+1)*2048+i]=h[j];\n") == 2
    block = block.replace("                if(group==0)trace[(layer+1)*2048+i]=h[j];\n", "")
    block = block[:-len("        }")] + """        const float ffn_scale=steering_scales[7];
        if(ffn_scale!=0.0f)for(uint j=0;j<8;++j) {
            uint i=(tid+(j/4)*256)*4+j%4;
            h[j]=flint_additive(h[j],steering[layer*2048+i],ffn_scale);
        }
        if(group==0)for(uint j=0;j<8;++j){uint i=(tid+(j/4)*256)*4+j%4;trace[(layer+1)*2048+i]=h[j];}
        }"""
    return body[:start] + block + body[end:]


def export(original, transforms, profile):
    chip, workers, mlp_workers, specialize, _filename, suffix = PROFILES[profile]
    header = literal(original, "_HEADER")
    body = literal(original, "_BODY")
    header = transforms["expert_teams"].transform(header, mlp_workers)
    header = transforms["resident_optimizations"].transform(header)
    header, body = render(header, workers, mlp_workers), render(body, workers, mlp_workers)
    header, body = transforms["rank_routing"].transform(header, body, mlp_workers)
    header, body = transforms["kv_teams"].transform(header, body, workers)
    model = types.SimpleNamespace(
        embedding=types.SimpleNamespace(bits=8), head=types.SimpleNamespace(bits=4),
        config={"mlx_export": {"routed_expert_bits": 4}},
    )
    header, body = transforms["mixed_bits"].transform(header, body, model, mlp_workers, specialize)
    header = transforms["activation_optimization"].transform(header)
    packet = transforms["resident_block"].transform(body, workers)
    packet = packet.replace("block_step<8u", "block_step<uint(sampling[0])")
    anchor = "if(index==0)profile[block_step*2+1]=block_input_token;"
    assert packet.count(anchor) == 1
    packet = packet.replace(anchor, anchor + """
        if(index==0)profile[16]=block_step+1u;
        bool stop=false;
        for(uint j=0;j<uint(sampling[1]);++j)
            stop=stop||block_input_token==uint(sampling[2+j]);
        if(stop)break;
""")
    # The GPU filtered packet chains scalar launches after EOS. Its inactive
    # parameter blocks must leave KV untouched, just like upstream's active flag.
    scalar = """
    if(parameters[3]==0u) {
        if(thread_index_in_threadgroup==0)diagnostic[threadgroup_position_in_grid.x]=0u;
        return;
    }
""" + body
    preamble = PREAMBLE.replace(
        "Apple M5 Max, 76 groups x 256 threads, 64 MLP/head groups.",
        f"Apple {chip}, {workers} groups x 256 threads, {mlp_workers} MLP/head groups.",
    )
    result = preamble + header + entry("flint_decode_scalar" + suffix, scalar)
    result += entry("flint_decode_greedy8" + suffix, packet, packet=True) + HELPERS
    # Preserve the entire ordinary library, including its compilation cost.
    # Load a separate active library only when vectors are supplied at startup.
    active = preamble + header + STEERING_HELPER
    scratch = "threadgroup float steering_reduction[8];\n"
    active_scalar = scratch + "const device float* steering_scales=(const device float*)configuration;\n" + steer_body(scalar)
    active_packet = scratch + "const device float* steering_scales=sampling;\n" + steer_body(packet)
    active += entry("flint_decode_scalar_steer" + suffix, active_scalar, steering=True)
    active += entry("flint_decode_greedy8_steer" + suffix, active_packet, packet=True, steering=True)
    assert "__WORKERS__" not in result and "__EPS__" not in result
    assert "__WORKERS__" not in active and "__EPS__" not in active
    additive = preamble + header + ADDITIVE_HELPER
    additive_scalar = "const device float* steering_scales=(const device float*)configuration;\n" + additive_body(scalar)
    additive_packet = "const device float* steering_scales=sampling;\n" + additive_body(packet)
    additive += entry("flint_decode_scalar_additive" + suffix, additive_scalar, steering=True)
    additive += entry("flint_decode_greedy8_additive" + suffix, additive_packet, packet=True, steering=True)
    return result, active, additive


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkout", nargs="?", type=Path, default=Path(__file__).resolve().parents[2] / "flint")
    parser.add_argument("--profile", choices=["all", *PROFILES], default="all")
    parser.add_argument("--output", type=Path, help="Output file, when exporting a single profile")
    args = parser.parse_args()
    if args.output is not None and args.profile == "all":
        parser.error("--output requires a single --profile")
    directory = args.checkout / "engine/src/rec_mlx/kernels"
    original = (directory / "megakernel.py").read_text()
    transforms = load_transforms(directory)
    output_directory = Path(__file__).resolve().parents[1] / "src/metal/flint"
    for profile in PROFILES if args.profile == "all" else [args.profile]:
        result, active, additive = export(original, transforms, profile)
        output = args.output or output_directory / PROFILES[profile][4]
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(result)
        print(f"{output}: {len(result.splitlines())} lines, {len(result)} bytes")
        active_output = output.with_stem(output.stem + "-steer")
        active_output.write_text(active)
        print(f"{active_output}: {len(active.splitlines())} lines, {len(active)} bytes")
        additive_output = output.with_stem(output.stem + "-additive")
        additive_output.write_text(additive)
        print(f"{additive_output}: {len(additive.splitlines())} lines, {len(additive)} bytes")
    # Preserve the source license alongside the derived shader.
    (output.parent / "LICENSE.rec").write_text((args.checkout / "LICENSE").read_text())


if __name__ == "__main__":
    main()
